"""
Lung-specific datasets backed by the consolidated HDF5 caches generated by the
new preprocessing pipeline.

This module provides light-weight PyTorch ``Dataset`` implementations for:

* Patch-level training data stored in ``processed_patches/<split>.h5``
* Full-image volumes stored in ``processed_images/<split>.h5``

Both datasets open the HDF5 file lazily inside each worker process, making them
suitable for multi-process ``DataLoader`` usage without duplicating the in-memory
arrays generated during preprocessing.
"""

from __future__ import annotations

import json
import threading
from pathlib import Path
from typing import Any, Dict, Iterable, List, Optional, Sequence, Tuple, Union

import h5py
import numpy as np
import torch
from torch.utils.data import Dataset


# Standard lobe order for embeddings / indexing
KNOWN_LOBES = [
    'left_upper_lobe',
    'left_lower_lobe',
    'right_upper_lobe',
    'right_middle_lobe',
    'right_lower_lobe'
]
LOBE_TO_INDEX = {name: idx + 1 for idx, name in enumerate(KNOWN_LOBES)}
UNKNOWN_LOBE_INDEX = 0
SIDE_TYPE_TO_INDEX = {
    'ipsilateral': 1,
    'contralateral': 2
}
ANATOMICAL_SIDE_TO_INDEX = {
    'left': 1,
    'right': 2
}

H5PathLike = Union[str, Path]

_ALLOWED_CHANNELS = {"dose", "ct", "fused"}


def _canonicalise_channel_name(name: Any) -> str:
    if name is None:
        raise ValueError("Channel name cannot be None")
    normalized = str(name).strip().lower()
    if normalized in {"dose", "dose_only"}:
        return "dose"
    if normalized in {"ct", "ct_only"}:
        return "ct"
    if normalized in {"fused", "fusion", "fused_image", "dose_fused"}:
        return "fused"
    raise ValueError(f"Unsupported channel specification: {name}")


def _channels_from_mode(mode: Optional[str]) -> Optional[List[str]]:
    if not mode:
        return None
    tokens = [
        token
        for token in str(mode).replace("-", "_").replace("+", "_").split("_")
        if token
    ]
    if not tokens:
        return None
    channels = []
    for token in tokens:
        try:
            channel = _canonicalise_channel_name(token)
        except ValueError:
            continue
        if channel not in channels:
            channels.append(channel)
    return channels or None


def _resolve_input_channels(
    *,
    explicit_channels: Optional[Sequence[Any]] = None,
    config_channels: Optional[Sequence[Any]] = None,
    explicit_mode: Optional[str] = None,
    config_mode: Optional[str] = None,
    default: Optional[Sequence[str]] = None,
) -> List[str]:
    candidates = None
    if explicit_channels:
        candidates = [_canonicalise_channel_name(ch) for ch in explicit_channels]
    elif config_channels:
        candidates = [_canonicalise_channel_name(ch) for ch in config_channels]
    elif explicit_mode:
        candidates = _channels_from_mode(explicit_mode)
    elif config_mode:
        candidates = _channels_from_mode(config_mode)
    elif default:
        candidates = [_canonicalise_channel_name(ch) for ch in default]
    else:
        candidates = ["dose"]
    seen = set()
    result: List[str] = []
    for channel in candidates:
        if channel in _ALLOWED_CHANNELS and channel not in seen:
            result.append(channel)
            seen.add(channel)
    if not result:
        raise ValueError(
            "No valid input channels resolved. Please specify at least one of "
            f"{sorted(_ALLOWED_CHANNELS)}."
        )
    return result


def _normalize_tensor(tensor: torch.Tensor, mode: Any) -> torch.Tensor:
    if isinstance(mode, bool):
        if not mode:
            return tensor
        mode = "minmax"
    if mode is None:
        return tensor
    mode = str(mode).lower()
    if mode in {"minmax", "unit", "unitrange"}:
        min_val = torch.min(tensor)
        max_val = torch.max(tensor)
        range_val = max_val - min_val
        if torch.abs(range_val) > 1e-8:
            tensor = (tensor - min_val) / range_val
        else:
            tensor = tensor - min_val
    elif mode in {"zscore", "standard"}:
        mean = torch.mean(tensor)
        std = torch.std(tensor)
        if torch.abs(std) > 1e-8:
            tensor = (tensor - mean) / std
        else:
            tensor = tensor - mean
    elif mode in {"none"}:
        return tensor
    else:
        raise ValueError(f"Unsupported normalization mode '{mode}'")
    return tensor


def _compute_fused_channel(
    ct_tensor: torch.Tensor,
    dose_tensor: torch.Tensor,
    fusion_cfg: Optional[Dict[str, Any]] = None,
) -> torch.Tensor:
    cfg = fusion_cfg or {}
    method = str(cfg.get("method", "weighted_sum")).lower()

    if method in {"weighted_sum", "weighted"}:
        dose_weight = float(cfg.get("dose_weight", 0.5))
        ct_weight = float(cfg.get("ct_weight", 0.5))
        fused = dose_tensor * dose_weight + ct_tensor * ct_weight
    elif method == "mean":
        fused = 0.5 * (dose_tensor + ct_tensor)
    elif method == "max":
        fused = torch.maximum(dose_tensor, ct_tensor)
    elif method == "min":
        fused = torch.minimum(dose_tensor, ct_tensor)
    elif method == "dose":
        fused = dose_tensor.clone()
    elif method == "ct":
        fused = ct_tensor.clone()
    else:
        raise ValueError(
            f"Unsupported fusion method '{method}'. Supported methods: "
            "weighted_sum, mean, max, min, dose, ct."
        )

    if cfg.get("clamp", False):
        min_val = cfg.get("clamp_min", 0.0)
        max_val = cfg.get("clamp_max", 1.0)
        fused = fused.clamp(min=float(min_val), max=float(max_val))

    if "normalize" in cfg:
        fused = _normalize_tensor(fused, cfg["normalize"])

    return fused.to(dtype=torch.float32)


def _assemble_input_tensor(
    channels: Sequence[str],
    ct_tensor: torch.Tensor,
    dose_tensor: torch.Tensor,
    fusion_cfg: Optional[Dict[str, Any]] = None,
) -> Tuple[torch.Tensor, Dict[str, torch.Tensor]]:
    available = {
        "ct": ct_tensor,
        "dose": dose_tensor,
    }
    if "fused" in channels:
        available["fused"] = _compute_fused_channel(ct_tensor, dose_tensor, fusion_cfg)

    tensors = [available[ch] for ch in channels]
    input_tensor = torch.cat(tensors, dim=0)
    return input_tensor, available


class BaseH5Dataset(Dataset):
    """
    Shared utilities for datasets backed by a single HDF5 file.
    """

    def __init__(self, h5_path: H5PathLike, transform: Optional[Any] = None):
        self.h5_path = Path(h5_path)
        if not self.h5_path.exists():
            raise FileNotFoundError(f"HDF5 dataset not found: {self.h5_path}")

        self.transform = transform
        self._h5_file: Optional[h5py.File] = None
        self._file_lock = threading.Lock()

    def _require_file(self) -> h5py.File:
        with self._file_lock:
            if self._h5_file is None:
                self._h5_file = h5py.File(self.h5_path, "r")
        return self._h5_file

    def close(self) -> None:
        with self._file_lock:
            if self._h5_file is not None:
                try:
                    self._h5_file.close()
                finally:
                    self._h5_file = None

    def __enter__(self):
        self._require_file()
        return self

    def __exit__(self, exc_type, exc_val, exc_tb):
        self.close()

    def __del__(self):
        try:
            self.close()
        except Exception:
            pass

    def __getstate__(self):
        state = self.__dict__.copy()
        state["_h5_file"] = None
        return state

    @staticmethod
    def _decode_hdf5_json_blob(blob: Any) -> str:
        if isinstance(blob, np.ndarray):
            blob = blob.tobytes()
        if isinstance(blob, (bytes, bytearray, np.bytes_)):
            return blob.decode("utf-8")
        if isinstance(blob, str):
            return blob
        return str(blob)


class PatchDataset(BaseH5Dataset):
    """
    Patch-level dataset backed by the consolidated HDF5 cache produced by the
    :class:`LungPreprocessor`.
    """

    def __init__(
        self,
        h5_path: H5PathLike,
        config: Optional[Dict[str, Any]] = None,
        *,
        apply_transforms: Optional[bool] = None,
        input_channels: Optional[Sequence[Any]] = None,
        transform: Optional[Any] = None,
        input_mode: Optional[str] = None,
        side: Optional[str] = None,
        patient_ids: Optional[Sequence[str]] = None,
        indices: Optional[Sequence[int]] = None,
        return_metadata: bool = True,
        fusion_config: Optional[Dict[str, Any]] = None,
    ):
        super().__init__(h5_path, transform=transform)

        self.config = config or {}
        dataset_cfg = self.config.get("dataset", {})

        config_channels = dataset_cfg.get("input_channels")
        if config_channels is None:
            config_channels = dataset_cfg.get("modalities")

        self.input_channels = _resolve_input_channels(
            explicit_channels=input_channels,
            config_channels=config_channels,
            explicit_mode=input_mode,
            config_mode=dataset_cfg.get("input_mode"),
        )
        self.fusion_config = {}
        self.fusion_config.update(dataset_cfg.get("fusion", {}))
        if fusion_config:
            self.fusion_config.update(fusion_config)

        cfg_apply = dataset_cfg.get("apply_transforms")
        if apply_transforms is not None:
            self.apply_transforms = bool(apply_transforms)
        elif cfg_apply is not None:
            self.apply_transforms = bool(cfg_apply)
        else:
            self.apply_transforms = True

        self.input_mode = "+".join(self.input_channels)
        self.return_metadata = return_metadata

        with h5py.File(self.h5_path, "r") as f:
            required_datasets = ["ct_patches", "dose_patches", "spatial_coords"]
            missing = [name for name in required_datasets if name not in f]
            if missing:
                raise KeyError(
                    f"HDF5 file {self.h5_path} is missing datasets: {', '.join(missing)}"
                )

            self._total_patches = int(f["ct_patches"].shape[0])
            self.patch_shape: Tuple[int, int, int] = tuple(f["ct_patches"].shape[1:])
            self.file_attrs: Dict[str, Any] = dict(f.attrs)

            self._ipsi_indices = f["ipsi_indices"][:].astype(np.int64)
            self._contra_indices = f["contra_indices"][:].astype(np.int64)
            self._ipsi_set = set(int(i) for i in self._ipsi_indices.tolist())
            self._contra_set = set(int(i) for i in self._contra_indices.tolist())

            metadata_blob = self._decode_hdf5_json_blob(f["patch_metadata"][()])
            self.patch_metadata: List[Dict[str, Any]] = (
                json.loads(metadata_blob) if metadata_blob else []
            )

            lobe_blob = self._decode_hdf5_json_blob(f["lobe_mapping"][()])
            self.lobe_mapping: Dict[str, Dict[str, List[int]]] = (
                json.loads(lobe_blob) if lobe_blob else {}
            )

            summary_blob = self._decode_hdf5_json_blob(f["patient_summary"][()])
            self.patient_summary: Dict[str, Any] = (
                json.loads(summary_blob) if summary_blob else {}
            )

        self._min_dose = float(dataset_cfg.get("min_dose", 0.0) or 0.0)
        self._patient_to_indices = self._build_patient_index()
        self._dose_mask = self._build_dose_mask()
        self._indices = self._build_active_index(indices, side, patient_ids)

    def _build_patient_index(self) -> Dict[str, List[int]]:
        mapping: Dict[str, List[int]] = {}
        for idx, meta in enumerate(self.patch_metadata):
            patient_id = meta.get("patient_id")
            if not patient_id:
                continue
            mapping.setdefault(patient_id, []).append(idx)
        return mapping

    def _build_dose_mask(self) -> np.ndarray:
        if self._min_dose <= 0:
            return np.ones(self._total_patches, dtype=bool)
        mask = np.ones(self._total_patches, dtype=bool)
        for idx, meta in enumerate(self.patch_metadata):
            dose_max = meta.get("dose_max")
            if dose_max is None:
                continue
            try:
                if float(dose_max) <= self._min_dose:
                    mask[idx] = False
            except (TypeError, ValueError):
                continue
        return mask

    def _normalise_side(self, side: Optional[str]) -> Optional[str]:
        if not side:
            return None
        side = side.lower()
        if side in {"ipsi", "ipsilateral"}:
            return "ipsilateral"
        if side in {"contra", "contralateral"}:
            return "contralateral"
        raise ValueError("side must be one of {'ipsilateral', 'contralateral'}")

    def _build_active_index(
        self,
        indices: Optional[Sequence[int]],
        side: Optional[str],
        patient_ids: Optional[Sequence[str]],
    ) -> np.ndarray:
        active: Iterable[int]

        if indices is not None:
            active = [int(i) for i in indices]
        else:
            side = self._normalise_side(side)
            if side == "ipsilateral":
                active = self._ipsi_indices.tolist()
            elif side == "contralateral":
                active = self._contra_indices.tolist()
            else:
                active = range(self._total_patches)

        active_array = np.array(list(active), dtype=np.int64)

        if patient_ids:
            wanted = set(patient_ids)
            active_array = np.array(
                [
                    idx
                    for idx in active_array
                    if self._metadata_for_index(idx).get("patient_id") in wanted
                ],
                dtype=np.int64,
            )

        if self._dose_mask is not None:
            valid = self._dose_mask[active_array]
            active_array = active_array[valid]

        if active_array.size == 0:
            raise ValueError(
                "No patches available after applying dataset filters. "
                "Consider lowering 'dataset.min_dose' or disabling test_mode."
            )

        return active_array

    def _metadata_for_index(self, index: int) -> Dict[str, Any]:
        if 0 <= index < len(self.patch_metadata):
            return self.patch_metadata[index]
        return {}

    def __len__(self) -> int:
        return int(self._indices.size)

    def __getitem__(self, item: int) -> Dict[str, Any]:
        global_index = int(self._indices[item])
        h5_file = self._require_file()

        ct_patch = np.asarray(h5_file["ct_patches"][global_index], dtype=np.float32)
        dose_patch = np.asarray(h5_file["dose_patches"][global_index], dtype=np.float32)
        coords = np.asarray(h5_file["spatial_coords"][global_index], dtype=np.int64)

        ct_tensor = torch.from_numpy(ct_patch).unsqueeze(0)
        dose_tensor = torch.from_numpy(dose_patch).unsqueeze(0)
        input_tensor, available_channels = _assemble_input_tensor(
            self.input_channels, ct_tensor, dose_tensor, self.fusion_config
        )

        metadata = self._metadata_for_index(global_index)
        metadata = dict(metadata) if metadata else {}
        if not self.return_metadata:
            metadata = {}

        side_type = metadata.get("side_type")
        if not side_type:
            if global_index in self._ipsi_set:
                side_type = "ipsilateral"
            elif global_index in self._contra_set:
                side_type = "contralateral"
            else:
                side_type = "unknown"

        sample: Dict[str, Any] = {
            "index": global_index,
            "input": input_tensor,
            "image": input_tensor,
            "channels": tuple(self.input_channels),
            "ct": ct_tensor,
            "dose": dose_tensor,
            "spatial_coords": torch.from_numpy(coords),
            "metadata": metadata,
            "patient_id": metadata.get("patient_id"),
            "side_type": side_type,
            "is_ipsilateral": global_index in self._ipsi_set,
        }

        lobe_name = metadata.get("lobe_name", "unknown")
        anatomical_side = metadata.get("anatomical_side", "unknown")
        sample["lobe_name"] = lobe_name
        sample["anatomical_side"] = anatomical_side
        sample["organ_ratio"] = metadata.get("organ_ratio")
        sample["lobe_index"] = LOBE_TO_INDEX.get(lobe_name, UNKNOWN_LOBE_INDEX)
        sample["side_type_index"] = SIDE_TYPE_TO_INDEX.get(side_type, 0)
        sample["anatomical_side_index"] = ANATOMICAL_SIDE_TO_INDEX.get(anatomical_side, 0)
        if "fused" in available_channels:
            sample["fused"] = available_channels["fused"]

        if self.transform is not None and self.apply_transforms:
            sample = self.transform(sample)

        return sample

    @property
    def indices(self) -> np.ndarray:
        return self._indices.copy()

    @property
    def total_patches(self) -> int:
        return self._total_patches

    def get_patient_indices(self, patient_id: str, restrict_to_active: bool = True) -> List[int]:
        indices = self._patient_to_indices.get(patient_id, [])
        if not restrict_to_active:
            return list(indices)
        active = set(self._indices.tolist())
        return [idx for idx in indices if idx in active]

    def get_patient_ids(self) -> List[str]:
        return list(self._patient_to_indices.keys())

    def get_ipsilateral_indices(self, restrict_to_active: bool = True) -> List[int]:
        indices = self._ipsi_indices.tolist()
        if not restrict_to_active:
            return indices
        active = set(self._indices.tolist())
        return [idx for idx in indices if idx in active]

    def get_contralateral_indices(self, restrict_to_active: bool = True) -> List[int]:
        indices = self._contra_indices.tolist()
        if not restrict_to_active:
            return indices
        active = set(self._indices.tolist())
        return [idx for idx in indices if idx in active]

    def describe(self) -> Dict[str, Any]:
        return {
            "file": str(self.h5_path),
            "total_patches": self._total_patches,
            "active_patches": len(self),
            "patch_shape": self.patch_shape,
            "input_mode": self.input_mode,
            "input_channels": tuple(self.input_channels),
            "apply_transforms": self.apply_transforms,
            "attributes": self.file_attrs,
        }


    def get_lobe_indices(
        self,
        lobe_name: str,
        side_type: str = "ipsilateral",
        restrict_to_active: bool = True,
    ) -> List[int]:
        side_type = side_type.lower()
        mapping = self.lobe_mapping.get(side_type, {})
        indices = mapping.get(lobe_name, [])
        if not restrict_to_active:
            return list(indices)

        active = set(self.indices.tolist())
        return [idx for idx in indices if idx in active]

    def get_patient_lobe_indices(
        self,
        patient_id: str,
        lobe_name: str,
        side_type: Optional[str] = None,
        restrict_to_active: bool = True,
    ) -> List[int]:
        candidate_indices = self.get_lobe_indices(
            lobe_name, side_type or "ipsilateral", restrict_to_active=False
        )
        patient_indices = set(self.get_patient_indices(patient_id, restrict_to_active=False))

        filtered = [idx for idx in candidate_indices if idx in patient_indices]
        if restrict_to_active:
            active = set(self.indices.tolist())
            filtered = [idx for idx in filtered if idx in active]
        return filtered

    def describe_lobes(self) -> Dict[str, Dict[str, int]]:
        summary: Dict[str, Dict[str, int]] = {}
        active = set(self.indices.tolist())
        for side_type, lobes in self.lobe_mapping.items():
            summary[side_type] = {}
            for lobe_name, indices in lobes.items():
                summary[side_type][lobe_name] = sum(1 for idx in indices if idx in active)
        return summary

class ImageH5Dataset(BaseH5Dataset):
    """
    Full-image dataset backed by the consolidated HDF5 cache generated by the
    lung preprocessing pipeline.
    """

    def __init__(
        self,
        h5_path: H5PathLike,
        *,
        transform: Optional[Any] = None,
        input_mode: Optional[str] = None,
        patient_ids: Optional[Sequence[str]] = None,
        config: Optional[Dict[str, Any]] = None,
        input_channels: Optional[Sequence[Any]] = None,
        fusion_config: Optional[Dict[str, Any]] = None,
        apply_transforms: Optional[bool] = None,
    ):
        super().__init__(h5_path, transform=transform)

        self.config = config or {}
        dataset_cfg = self.config.get("dataset", {})

        config_channels = dataset_cfg.get("input_channels")
        if config_channels is None:
            config_channels = dataset_cfg.get("modalities")
        self.input_channels = _resolve_input_channels(
            explicit_channels=input_channels,
            config_channels=config_channels,
            explicit_mode=input_mode,
            config_mode=dataset_cfg.get("input_mode"),
        )
        self.fusion_config = {}
        self.fusion_config.update(dataset_cfg.get("fusion", {}))
        if fusion_config:
            self.fusion_config.update(fusion_config)

        cfg_apply = dataset_cfg.get("apply_transforms")
        if apply_transforms is not None:
            self.apply_transforms = bool(apply_transforms)
        elif cfg_apply is not None:
            self.apply_transforms = bool(cfg_apply)
        else:
            self.apply_transforms = True

        self.input_mode = "+".join(self.input_channels)

        with h5py.File(self.h5_path, "r") as f:
            all_patients = sorted(list(f.keys()))
            if patient_ids:
                requested = set(patient_ids)
                missing = requested - set(all_patients)
                if missing:
                    raise KeyError(
                        f"Patients not present in {self.h5_path}: {', '.join(sorted(missing))}"
                    )
                self._patient_ids = [pid for pid in all_patients if pid in requested]
            else:
                self._patient_ids = all_patients

            self.file_attrs: Dict[str, Any] = dict(f.attrs)

        if not self._patient_ids:
            raise ValueError(f"No patient groups found in {self.h5_path}")

    def __len__(self) -> int:
        return len(self._patient_ids)

    def __getitem__(self, item: int) -> Dict[str, Any]:
        patient_id = self._patient_ids[item]
        h5_file = self._require_file()
        group = h5_file[patient_id]

        ct_volume = np.asarray(group["ct"][()], dtype=np.float32)
        dose_volume = np.asarray(group["dose"][()], dtype=np.float32)

        ct_tensor = torch.from_numpy(ct_volume).unsqueeze(0)
        dose_tensor = torch.from_numpy(dose_volume).unsqueeze(0)
        input_tensor, available_channels = _assemble_input_tensor(
            self.input_channels, ct_tensor, dose_tensor, self.fusion_config
        )

        spacing = tuple(np.asarray(group["ct"].attrs.get("spacing", ()), dtype=np.float32))
        origin = tuple(np.asarray(group["ct"].attrs.get("origin", ()), dtype=np.float32))
        direction = tuple(np.asarray(group["ct"].attrs.get("direction", ()), dtype=np.float32))

        sample: Dict[str, Any] = {
            "patient_id": patient_id,
            "input": input_tensor,
            "image": input_tensor,
            "channels": tuple(self.input_channels),
            "ct": ct_tensor,
            "dose": dose_tensor,
            "spacing": spacing,
            "origin": origin,
            "direction": direction,
            "attributes": dict(group.attrs),
        }
        if "fused" in available_channels:
            sample["fused"] = available_channels["fused"]

        if self.transform is not None and self.apply_transforms:
            sample = self.transform(sample)

        return sample

    def describe(self) -> Dict[str, Any]:
        return {
            "file": str(self.h5_path),
            "patients": len(self._patient_ids),
            "input_mode": self.input_mode,
            "input_channels": tuple(self.input_channels),
            "apply_transforms": self.apply_transforms,
            "attributes": self.file_attrs,
        }
